// Real execution invariants: partial fills, target stages, exchange dates, cash and risk limits.
const assert = require('node:assert/strict'), fs = require('node:fs');
const T = require('../scoring/trading.js');
const ctx = T.configure({ calendar: JSON.parse(fs.readFileSync(require.resolve('../scoring/calendar.json'), 'utf8')) });
const row = { k: '005930', n: '삼성전자', s: '전자', p: 1000, rk: 1, ch: 0, stopPct: -.2 };
const pos = qty => ({ qty, avg: 1000, maxP: 1000, firstD: '2026-10-01', lastD: '2026-10-01', stopPct: -.2, upPct: .4, events: [], completedStages: [] });
const cfg = { capital: 300000, slots: 10 };
const series = [{ d: '2026-10-01', c: 1300 }, { d: '2026-10-02', c: 1000 }, { d: '2026-10-06', c: 1200 }, { d: '2026-10-07', c: 900 }];
assert.deepEqual(T.peakSeries(series), [['2026-10-01', 1300], ['2026-10-06', 1200], ['2026-10-07', 900]]);
const input = more => ({ rows: { [row.k]: row }, positions: {}, recs: [row.k], signalDate: '2026-09-30', executionDate: '2026-10-01', cash: 300000, equity: 300000, slots: 10, context: ctx, ...more });
assert.equal(ctx.calendar.next('2026-09-23'), '2026-09-28');
assert.equal(ctx.calendar.next('2026-10-02'), '2026-10-06');
assert.equal(ctx.calendar.next('2026-06-02'), '2026-06-04');
assert.equal(ctx.calendar.next('2026-12-30'), '2027-01-04');
assert.equal(ctx.calendar.next('2028-12-31'), null);
let plan = T.orders(input()).items[0];
assert.equal(plan.qty, 10); assert.equal(plan.goalQty, 10); assert.equal(plan.fullTargetQty, 30);
const fill = qty => ({ code: row.k, date: plan.date, side: 'buy', qty, price: 1000 });
assert.deepEqual(T.progress(plan, [fill(3), fill(2)]), { filled: 5, remaining: 5, excess: 0, count: 2, status: 'partial' });
assert.equal(T.progress(plan, [fill(12)]).status, 'overfilled');
assert.equal(T.progress({ ...plan, cancelled: true }, [fill(3)]).status, 'cancelled');
assert.equal(T.progress({ ...plan, cancelled: true }, [fill(10)]).status, 'filled');
assert.equal(T.progress(plan, [fill(10), { ...fill(99), date: '2026-10-02' }]).filled, 10);
assert.deepEqual(T.completedStages(row.k, pos(10), { [plan.id]: plan }, [fill(3), fill(7)]), [1]);
assert.deepEqual(T.completedStages(row.k, pos(30), { [plan.id]: plan }, [fill(30)]).sort(), [1, 2, 3]);
assert.deepEqual(T.completedStages(row.k, pos(20), { [plan.id]: plan }, [fill(20)]), [1, 2]);
assert.deepEqual(T.completedStages(row.k, pos(3), { [plan.id]: plan }, [fill(20), { ...fill(17), side: 'sell' }]), []);
assert.deepEqual(T.completedStages(row.k, { ...pos(3), events: [fill(3)] }, { [plan.id]: plan }, [fill(10), fill(3)]), []); // a fresh cycle after a same-day exit
assert.equal(T.manage(row, 0, pos(3), cfg, '2026-10-07', { context: ctx }).buyQty, 7);
assert.equal(T.manage(row, 0, pos(3), cfg, '2026-10-08', { context: ctx }).buyQty, 17);
assert.equal(T.manage(row, 0, pos(15), cfg, '2026-10-08', { context: ctx }).buyQty, 5);
assert.equal(T.manage(row, 0, pos(35), cfg, '2026-10-08', { context: ctx }).buyQty, undefined);
assert.equal(T.manage(row, 0, { ...pos(19), completedStages: [1, 2] }, cfg, '2026-10-12', { context: ctx }).buyQty, undefined);
assert.equal(T.manage(row, 0, { ...pos(3), buys: ['a', 'b', 'c', 'd'] }, cfg, '2026-10-07', { context: ctx }).buyQty, 7);
const failedCtx = { ...ctx, ranks: { '2026-10-02': { [row.k]: 30 } } };
assert.equal(T.manage(row, 0, { ...pos(3), lastD: '2026-10-07' }, cfg, '2026-10-08', { context: failedCtx }).buyQty, undefined);
assert.match(T.manage(row, 0, pos(3), cfg, '2026-10-08', { context: failedCtx }).reason, /재평가/); // separate recovery after cooldown
const out = { ...row, rk: 50 }, trim = T.manage(out, 3, pos(90), cfg, '2026-10-08', { context: ctx });
assert.equal(trim.sellQty, 45);
assert.equal(T.manage(out, 3, { ...pos(60), events: [{ decision: trim.decision, side: 'sell', qty: 30 }] }, cfg, '2026-10-12', { context: ctx }).sellQty, 15);
assert.equal(T.manage(out, 3, { ...pos(45), events: [{ decision: trim.decision, side: 'sell', qty: 45 }] }, cfg, '2026-10-12', { context: ctx }).sellQty, undefined);
const regularTrim = T.manage(out, 3, pos(30), cfg, '2026-10-08', { context: ctx });
assert.equal(T.manage(out, 3, { ...pos(18), events: [{ decision: regularTrim.decision, side: 'sell', qty: 12 }] }, cfg, '2026-10-12', { context: ctx }).sellQty, 3);
const second = { ...row, k: '105560' };
const noProceeds = T.orders(input({ rows: { [row.k]: { ...row, rk: 90 }, [second.k]: second }, positions: { [row.k]: pos(10) }, recs: [second.k], cash: 0 }));
assert.equal(noProceeds.items.filter(o => o.side === 'buy').length, 0);
assert.equal(noProceeds.items[0].side, 'sell');
assert.equal(T.orders(input({ cash: 2500 })).items[0].qty, 2);
assert.equal(T.orders(input({ cash: 2500, policy: { cashReserve: .03 } })).cash, 2500);
assert.equal(T.orders(input({ rows: { [row.k]: { ...row, p: 0 } } })).items.length, 0);
assert.equal(T.manage({ ...row, p: 700, rk: null }, null, pos(3), cfg, '2026-10-08', { context: ctx }).k, 'stop');
assert.equal(T.orders(input({ policy: { riskFraction: .01 } })).items[0].fullTargetQty, 15);
const sector = T.orders(input({ rows: { [row.k]: row, [second.k]: second }, recs: [row.k, second.k], policy: { maxSector: .04 } }));
assert.equal(sector.items.reduce((s, p) => s + p.qty * p.price, 0), 12000);
assert.equal(T.orders(input({ executionDate: '2026-10-03' })).items.length, 0);
assert.equal(T.orders(input({ rows: { [row.k]: { ...row, old: '2026-09-28' } } })).items.length, 0);
assert.equal(T.manage(row, 0, pos(3), cfg, '2030-01-01', { context: ctx }).k, 'calendar');
assert.equal(Object.keys(T.mergePlans({}, { bad: { ...plan, qty: -1 }, good: plan })).length, 1);
console.log('Trading: partial/extra fills, cumulative stages, holiday calendar, cancellations, trim residuals, cash, sizing, stale data and compatible plan restore passed.');
